import assert from "node:assert/strict";
import {groupEnabled,groupMoney,groupWithinBudget,distinctGroupIdentities,groupDocumentConflict,sharedDocumentCode} from "../src/lib/group-policy";
import {CONSOLIDATED_BRANCH} from "../src/lib/traveller-hub-policy";
assert.equal(groupEnabled({VERCEL_ENV:"production",VERCEL_GIT_COMMIT_REF:CONSOLIDATED_BRANCH,DATABASE_SCHEMA:"visa_os_preview"}),false);
assert.equal(groupEnabled({VERCEL_ENV:"preview",VERCEL_GIT_COMMIT_REF:CONSOLIDATED_BRANCH,DATABASE_SCHEMA:"visa_os"}),false);
assert.equal(groupEnabled({VERCEL_ENV:"preview",VERCEL_GIT_COMMIT_REF:CONSOLIDATED_BRANCH,DATABASE_SCHEMA:"visa_os_preview"}),true);
assert.equal(groupMoney("11000.00",4),4400000);
assert.equal(groupMoney("10.25",3),3075);
assert.equal(groupMoney("NaN",3),null);
assert.equal(groupMoney("1.001",3),null);
assert.equal(groupWithinBudget(1,0,0),false);
assert.equal(groupWithinBudget(6,0,0),false);
assert.equal(groupWithinBudget(5,31,0),false);
assert.equal(groupWithinBudget(5,30,24*1024*1024+1),false);
assert.equal(groupWithinBudget(5,30,24*1024*1024),true);
assert.equal(distinctGroupIdentities([{passportNumber:"123456"},{passportNumber:"123457"}]),true);
assert.equal(distinctGroupIdentities([{passportNumber:"123456"},{passportNumber:"123456"}]),false);
assert.equal(distinctGroupIdentities([{passportNumber:"123456",travellerProfileId:"same"},{passportNumber:"123457",travellerProfileId:"same"}]),false);
assert.equal(distinctGroupIdentities([{passportNumber:""},{passportNumber:"123457"}]),false);
assert.equal(sharedDocumentCode("PASSPORT"),false);
assert.equal(sharedDocumentCode("HOTEL_RESERVATION"),true);
assert.equal(groupDocumentConflict([{member:1,code:"PASSPORT",sha256:"x"},{member:2,code:"PASSPORT",sha256:"x"}]),true);
assert.equal(groupDocumentConflict([{member:1,code:"PASSPORT",sha256:"x"},{member:2,code:"HOTEL_RESERVATION",sha256:"x"}]),true);
assert.equal(groupDocumentConflict([{member:1,code:"HOTEL_RESERVATION",sha256:"x"},{member:2,code:"HOTEL_RESERVATION",sha256:"x"}]),false);
assert.equal(groupDocumentConflict([{member:1,code:"PASSPORT",sha256:"x"},{member:2,code:"PASSPORT",sha256:"y"}]),false);
console.log("[group-booking] Scope, monetary arithmetic, caps, identities and shared-file conflict PASS (22 assertions)");
