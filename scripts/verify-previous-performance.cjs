const fs=require("node:fs");const path=require("node:path");
const kind=process.env.PERF_RUN_KIND||"TIER";
const vus=Number(process.env.PERF_VUS);
if(!["TIER","SOAK","SPIKE"].includes(kind))throw new Error("Unknown qualification profile.");
if(kind==="SOAK"&&![100,250].includes(vus))throw new Error("Soak requires a proven 100/250-VU tier.");
if(kind==="SPIKE"&&vus!==250)throw new Error("Spike requires the proven 250-VU tier.");
const expected=kind==="TIER"?{50:10,100:50,250:100,500:250,1000:500}[vus]:vus;
if(!expected)throw new Error("No preceding tier is defined.");
const candidates=[];
function walk(dir){for(const item of fs.readdirSync(dir,{withFileTypes:true})){const file=path.join(dir,item.name);if(item.isDirectory())walk(file);else if(item.name==="tier.json")candidates.push(file);}}
walk(process.argv[2]);
const matched=candidates.filter(file=>{const tier=JSON.parse(fs.readFileSync(file,"utf8"));return tier.sha===process.env.GITHUB_SHA&&tier.baseUrl===process.env.BASE_URL&&tier.schema==="visa_os_preview"&&(tier.kind||"TIER")==="TIER"&&tier.vus===expected&&tier.holdMinutes>=20&&tier.status==="PASS";});
if(matched.length!==1)throw new Error("Passing preceding tier proof is missing or ambiguous.");
const dir=path.dirname(matched[0]);
for(const name of ["db-before.json","db-monitor.json","db-after.json","k6-summary.json","evaluation.json"])if(!fs.statSync(path.join(dir,name)).size)throw new Error("Mandatory previous-tier artifact is empty.");
const evaluation=JSON.parse(fs.readFileSync(path.join(dir,"evaluation.json"),"utf8"));
if(!evaluation.checks.length||!evaluation.checks.every(check=>check.pass===true))throw new Error("Previous-tier evaluation failed.");
const tier=JSON.parse(fs.readFileSync(matched[0],"utf8"));
const monitor=JSON.parse(fs.readFileSync(path.join(dir,"db-monitor.json"),"utf8"));
if(monitor.samplingFailed||!monitor.samples?.length)throw new Error("Previous-tier monitoring is incomplete.");
const first=Date.parse(monitor.samples[0].at),last=Date.parse(monitor.samples.at(-1).at);
const started=Date.parse(tier.k6StartedAt),finished=Date.parse(tier.k6FinishedAt);
if(![first,last,started,finished].every(Number.isFinite)||first>started||last<finished-Math.max(2000,2*monitor.intervalMs))throw new Error("Database monitoring does not cover the previous complete workload.");
console.log(`PASS preceding ${expected}-VU tier, exact SHA and Preview URL verified.`);
